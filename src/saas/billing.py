class RazorpayClient:
    """Lightweight, zero-dependency client for the Razorpay v1 REST API."""

    API_BASE = "https://api.razorpay.com/v1"

    def __init__(self, key_id: str, key_secret: str, timeout: float = 10.0):
        self.key_id = key_id
        self.key_secret = key_secret
        self.timeout = timeout

    def _auth_header(self) -> str:
        creds = f"{self.key_id}:{self.key_secret}".encode("utf-8")
        return f"Basic {base64.b64encode(creds).decode('utf-8')}"

    def create_order(
        self, amount_paise: int, currency: str = "INR", receipt: str = "", notes: Optional[dict] = None
    ) -> Dict[str, Any]:
        """Create a new Razorpay Order."""
        url = f"{self.API_BASE}/orders"
        headers = {
            "Authorization": self._auth_header(),
            "Content-Type": "application/json",
            "User-Agent": "PhishGuardAI-Razorpay/1.0"
        }
        payload = {
            "amount": amount_paise,
            "currency": currency,
            "receipt": receipt or f"rcpt_{uuid.uuid4().hex[:10]}",
            "notes": notes or {}
        }
        req = urllib.request.Request(url, data=json.dumps(payload).encode("utf-8"), headers=headers, method="POST")

        with urllib.request.urlopen(req, timeout=self.timeout) as resp:
            return json.loads(resp.read().decode("utf-8"))

    @staticmethod
    def verify_payment_signature(order_id: str, payment_id: str, signature: str, key_secret: str) -> bool:
        """Verify HMAC-SHA256 signature generated by Razorpay Checkout."""
        if not (order_id and payment_id and signature and key_secret):
            return False

        message = f"{order_id}|{payment_id}".encode("utf-8")
        expected_sig = hmac.new(key_secret.encode("utf-8"), message, hashlib.sha256).hexdigest()
        return hmac.compare_digest(expected_sig, signature)

    @staticmethod
    def verify_webhook_signature(payload_bytes: bytes, signature: str, webhook_secret: str) -> bool:
        """Verify Razorpay webhook signature header (X-Razorpay-Signature)."""
        if not (payload_bytes and signature and webhook_secret):
            return False

        expected_sig = hmac.new(webhook_secret.encode("utf-8"), payload_bytes, hashlib.sha256).hexdigest()
        return hmac.compare_digest(expected_sig, signature)


class BillingManager:
    """Manages Razorpay subscriptions, order creation, and payment verification."""

    def __init__(
        self,
        db_manager: SaaSDataManager,
        razorpay_key_id: Optional[str] = None,
        razorpay_key_secret: Optional[str] = None,
        webhook_secret: Optional[str] = None,
        # Backwards compatibility kwargs:
        stripe_api_key: Optional[str] = None,
    ):
        self.db_manager = db_manager
        self.key_id = razorpay_key_id or os.getenv("RAZORPAY_KEY_ID")
        self.key_secret = razorpay_key_secret or os.getenv("RAZORPAY_KEY_SECRET")
        self.webhook_secret = webhook_secret or os.getenv("RAZORPAY_WEBHOOK_SECRET") or os.getenv("STRIPE_WEBHOOK_SECRET")

        self.client = None
        if self.key_id and self.key_secret:
            self.client = RazorpayClient(self.key_id, self.key_secret)

    def get_plans(self) -> List[Dict[str, Any]]:
        """Return the public subscription pricing matrix."""
        return list(PRICING_CATALOG.values())

    def create_razorpay_order(
        self,
        user_id: int,
        plan_tier: str,
        currency: str = "INR"
    ) -> Dict[str, Any]:
        """
        Create a Razorpay order for purchasing or upgrading a plan.
        Returns order credentials needed by Razorpay Checkout modal in browser.
        """
        plan_tier = plan_tier.lower()
        if plan_tier not in PRICING_CATALOG or plan_tier == PlanTier.FREE:
            raise ValueError(f"Invalid paid plan tier: '{plan_tier}'")

        user = self.db_manager.get_user_by_id(user_id)
        if not user:
            raise ValueError(f"User ID {user_id} not found.")

        plan_info = PRICING_CATALOG[plan_tier]
        amount_paise = plan_info["amount_paise"]
        receipt = f"pg_{user_id}_{plan_tier[:4]}_{int(uuid.uuid4().int % 100000)}"

        # 1. Live Razorpay Order via REST API
        if self.client:
            try:
                order_data = self.client.create_order(
                    amount_paise=amount_paise,
                    currency=currency,
                    receipt=receipt,
                    notes={"user_id": str(user_id), "plan_tier": plan_tier, "email": user["email"]}
                )
                return {
                    "success": True,
                    "order_id": order_data["id"],
                    "amount": order_data["amount"],
                    "currency": order_data["currency"],
                    "key_id": self.key_id,
                    "plan_tier": plan_tier,
                    "plan_name": plan_info["name"],
                    "user_email": user["email"],
                    "user_name": user.get("full_name") or "Developer",
                    "mode": "live"
                }
            except Exception as e:
                # Fallback to simulated mode if live API times out
                pass

        # 2. Simulated / Sandbox Razorpay Order (for dev & testing without live keys)
        mock_order_id = f"order_mock_{uuid.uuid4().hex[:14]}"
        return {
            "success": True,
            "order_id": mock_order_id,
            "amount": amount_paise,
            "currency": currency,
            "key_id": self.key_id or "rzp_test_mock_key_123",
            "plan_tier": plan_tier,
            "plan_name": plan_info["name"],
            "user_email": user["email"],
            "user_name": user.get("full_name") or "Developer",
            "mode": "mock"
        }

    def verify_and_activate_payment(
        self,
        user_id: int,
        plan_tier: str,
        order_id: str,
        payment_id: str,
        signature: str
    ) -> Dict[str, Any]:
        """
        Verify Razorpay HMAC signature and activate upgraded plan.
        """
        plan_tier = plan_tier.lower()
        if plan_tier not in PRICING_CATALOG or plan_tier == PlanTier.FREE:
            raise ValueError(f"Invalid paid plan tier: '{plan_tier}'")

        # In production with live credentials, verify cryptographic signature
        if self.key_secret:
            valid = RazorpayClient.verify_payment_signature(order_id, payment_id, signature, self.key_secret)
            if not valid:
                raise ValueError("Razorpay payment signature verification failed.")
        else:
            # Mock mode: verify mock signature format
            if not (order_id and payment_id):
                raise ValueError("Missing order or payment ID.")

        # Activate plan in database
        updated_user = self.db_manager.activate_razorpay_payment(
            user_id=user_id,
            plan_tier=plan_tier,
            payment_id=payment_id,
            order_id=order_id
        )

        return {
            "success": True,
            "message": f"Successfully activated {PRICING_CATALOG[plan_tier]['name']}!",
            "user": updated_user
        }

    def handle_webhook(self, payload_bytes: bytes, sig_header: Optional[str] = None) -> Dict[str, Any]:
        """
        Process Razorpay webhooks (order.paid, payment.captured, subscription.cancelled).
        Also supports backwards-compatible event structures.
        """
        if self.webhook_secret and sig_header:
            valid = RazorpayClient.verify_webhook_signature(payload_bytes, sig_header, self.webhook_secret)
            if not valid:
                raise ValueError("Invalid Razorpay Webhook Signature.")

        try:
            event = json.loads(payload_bytes.decode("utf-8"))
        except Exception as e:
            raise ValueError(f"Invalid JSON webhook payload: {str(e)}")

        event_type = event.get("event") or event.get("type", "")
        payload = event.get("payload", {})

        # Handle Razorpay payment.captured or order.paid
        if event_type in ("payment.captured", "order.paid"):
            payment_entity = payload.get("payment", {}).get("entity", {})
            order_entity = payload.get("order", {}).get("entity", {})

            notes = payment_entity.get("notes") or order_entity.get("notes") or {}
            user_id = notes.get("user_id")
            plan_tier = notes.get("plan_tier")

            payment_id = payment_entity.get("id") or "pay_webhook_captured"
            order_id = payment_entity.get("order_id") or order_entity.get("id") or "order_webhook"

            if user_id and plan_tier:
                updated_user = self.db_manager.activate_razorpay_payment(
                    user_id=int(user_id),
                    plan_tier=plan_tier,
                    payment_id=payment_id,
                    order_id=order_id
                )
                return {
                    "status": "processed",
                    "event": event_type,
                    "action": "activate_plan",
                    "user_id": int(user_id),
                    "plan_tier": plan_tier,
                    "user": updated_user
                }

        # Backwards compatible checkout.session.completed
        elif event_type == "checkout.session.completed":
            data_object = event.get("data", {}).get("object", {})
            metadata = data_object.get("metadata", {})
            user_id = metadata.get("user_id") or data_object.get("client_reference_id")
            plan_tier = metadata.get("plan_tier")
            if user_id and plan_tier:
                updated_user = self.db_manager.update_user_plan(
                    user_id=int(user_id),
                    plan_tier=plan_tier,
                    stripe_customer_id=data_object.get("customer"),
                    stripe_subscription_id=data_object.get("subscription")
                )
                return {"status": "processed", "event": event_type, "plan_tier": plan_tier, "user": updated_user}

        # Invoice payment succeeded -> Reset monthly quota
        elif event_type in ("invoice.payment_succeeded", "subscription.charged"):
            customer_id = payload.get("subscription", {}).get("entity", {}).get("customer_id") or event.get("data", {}).get("object", {}).get("customer")
            if customer_id:
                user = self.db_manager.get_user_by_razorpay_customer_id(customer_id) or self.db_manager.get_user_by_stripe_customer_id(customer_id)
                if user:
                    self.db_manager.reset_monthly_scans(user["id"])
                    return {"status": "processed", "action": "reset_monthly_scans", "user_id": user["id"]}

        # Subscription canceled -> Downgrade to Free
        elif event_type in ("subscription.cancelled", "customer.subscription.deleted"):
            customer_id = payload.get("subscription", {}).get("entity", {}).get("customer_id") or event.get("data", {}).get("object", {}).get("customer")
            if customer_id:
                user = self.db_manager.get_user_by_razorpay_customer_id(customer_id) or self.db_manager.get_user_by_stripe_customer_id(customer_id)
                if user:
                    updated_user = self.db_manager.update_user_plan(
                        user_id=user["id"], plan_tier=PlanTier.FREE, subscription_status="canceled"
                    )
                    return {"status": "processed", "action": "downgrade_to_free", "user_id": user["id"]}

        return {"status": "ignored", "event": event_type}

    # =========================================================================
    # Compatibility methods
    # =========================================================================

    def create_checkout_session(self, user_id: int, plan_tier: str, success_url: str, cancel_url: str) -> Dict[str, Any]:
        """Creates Razorpay order and returns formatted checkout parameters."""
        order_info = self.create_razorpay_order(user_id=user_id, plan_tier=plan_tier)
        checkout_url = f"{success_url}?order_id={order_info['order_id']}&tier={plan_tier}&user_id={user_id}"
        return {
            "success": True,
            "session_id": order_info["order_id"],
            "order": order_info,
            "checkout_url": checkout_url,
            "mode": order_info["mode"]
        }

    def create_customer_portal_session(self, user_id: int, return_url: str) -> Dict[str, Any]:
        return {"success": True, "portal_url": return_url, "mode": "razorpay_self_serve"}
